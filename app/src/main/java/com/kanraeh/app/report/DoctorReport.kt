package com.kanraeh.app.report

import android.graphics.Paint
import android.graphics.pdf.PdfDocument
import com.kanraeh.app.core.Clock
import com.kanraeh.app.core.EventTypes
import com.kanraeh.app.core.FactorKeys
import com.kanraeh.app.core.Graph
import com.kanraeh.app.core.Time
import com.kanraeh.app.cycle.HairAreas
import com.kanraeh.app.meds.MedClass
import java.io.ByteArrayOutputStream

/** MODULE: report - one-page-ish PDF summary for her doctor, built only from her own logged data. */
object DoctorReport {
    suspend fun build(): ByteArray {
        val now = Clock.now(); val from = now - 90 * Time.DAY
        val attacks = Graph.db.attacks().all().filter { it.startTs >= from }
        val closed = attacks.filter { it.endTs != null }
        val avg = if (closed.isEmpty()) null else closed.map { it.endTs!! - it.startTs }.average().toLong()
        val longest = closed.maxOfOrNull { it.endTs!! - it.startTs }
        val patterns = Graph.patterns.analyze()
        val cyc = Graph.cycle.summary(now)
        val ev = Graph.db.events().between(from, now)
        val over = Graph.meds.overuse(now)
        val labs = Graph.db.events().latest(EventTypes.LAB, 100).groupBy { it.key }.map { it.value.first() }
        val hair = Graph.db.events().latest(EventTypes.HAIR, 200).groupBy { it.key }.mapValues { it.value.first().value?.toInt() ?: 0 }
        val lowMoodDays = ev.filter { it.type == EventTypes.MOOD && (it.key == "low" || it.key == "tearful" || it.key == "anxious") }.map { Time.startOfDay(it.ts) }.distinct().size

        val lines = mutableListOf<String>()
        lines += "KANRAEH SUMMARY  (${Time.fmtDate(from)} to ${Time.fmtDate(now)})"
        lines += ""
        lines += "MIGRAINE"
        lines += "Attacks in the last 90 days: ${attacks.size}"
        lines += "Average duration: ${avg?.let { Time.fmtDuration(it) } ?: "not enough data"}   Longest: ${longest?.let { Time.fmtDuration(it) } ?: "-"}"
        lines += "Months view: " + attacks.groupBy { Time.fmtDate(Time.startOfDay(it.startTs)).takeLast(3) }.entries.joinToString { "${it.key}: ${it.value.size}" }
        lines += ""
        lines += "FACTORS THAT SHOWED UP BEFORE ATTACKS (from her own data; association, not proof)"
        if (!patterns.enoughData) lines += "Not enough attacks logged yet (${patterns.totalAttacks})."
        patterns.patterns.take(8).forEach { lines += "- ${FactorKeys.label(it.factor)}: before ${it.hits} of ${it.total} attacks (${it.confidence.name.lowercase()} confidence)" }
        lines += ""
        lines += "CYCLE"
        lines += "Logged cycle lengths (days): ${cyc.lengthsDays.joinToString().ifBlank { "none" }}"
        lines += "Shortest ${cyc.shortest ?: "-"}, longest ${cyc.longest ?: "-"}, irregular: ${if (cyc.irregular) "yes" else "not established"}"
        lines += ""
        lines += "MEDICINES (last 30 days, painkiller days)"
        if (over.isEmpty()) lines += "No acute medicines logged."
        over.forEach { lines += "- ${it.med.label}: ${it.daysLast30} days (limit often used: ${it.limit})" }
        val treatments = ev.filter { it.type == EventTypes.MED && MedClass.from(it.key)?.monthlyLimitDays == null }.groupBy { it.text.substringBefore('|') }
        treatments.forEach { (n, l) -> lines += "- $n: logged ${l.size} times" }
        lines += ""
        lines += "LAB RESULTS (latest)"
        if (labs.isEmpty()) lines += "None logged."
        labs.forEach { lines += "- ${it.key}: ${it.value ?: ""} ${it.text} (${Time.fmtDate(it.ts)})" }
        lines += ""
        lines += "HAIR SCORE (sum of latest area scores 0-4): ${if (hair.isEmpty()) "not logged" else HairAreas.total(hair).toString()}"
        lines += "Days with low, anxious or tearful mood (90 days): $lowMoodDays"
        lines += ""
        lines += "Generated by Kanraeh from self-reported data. Not a diagnosis."

        val doc = PdfDocument()
        val paint = Paint().apply { textSize = 11f }
        var pageNo = 1; var y = 50f
        var page = doc.startPage(PdfDocument.PageInfo.Builder(595, 842, pageNo).create())
        lines.forEach { raw ->
            raw.chunked(95).ifEmpty { listOf("") }.forEach { line ->
                if (y > 800f) { doc.finishPage(page); pageNo++; page = doc.startPage(PdfDocument.PageInfo.Builder(595, 842, pageNo).create()); y = 50f }
                paint.isFakeBoldText = line.isNotEmpty() && line == line.uppercase() && line.length < 90
                page.canvas.drawText(line, 40f, y, paint); y += 16f
            }
        }
        doc.finishPage(page)
        val out = ByteArrayOutputStream(); doc.writeTo(out); doc.close()
        return out.toByteArray()
    }
}
